export function normalizeStadiumTheme(raw: unknown): StadiumTheme {
  if (raw === 'international' || raw === 'night' || raw === 'indoor' || raw === 'futuristic') {
    return raw;
  }
  if (raw === 'daylight') return 'international';
  if (raw === 'sunset') return 'night';
  return 'night';
}

